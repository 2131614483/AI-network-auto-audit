def fmt(x: Decimal) -> str:
    return f"{x:,.2f}"


def main() -> None:
    led = build_ledger()
    report: dict = {"checks": [], "entities": {}, "entries": len(ENTRIES)}

    for ent in ("P", "S1", "S2"):
        report["entities"][ent] = {
            "name": ENTITY_NAME[ent],
            "balance_check": str(balance_check(led[ent])),
            "trial_balance": {c: str(v) for c, v in sorted(led[ent].items())},
        }

    merged, elims = consolidate(led)

    # ---- 校验 ----
    def check(name, got, exp, tol="0.01"):
        ok = abs(q(got) - q(exp)) <= q(tol)
        report["checks"].append({"check": name, "actual": str(q(got)),
                                 "expected": str(q(exp)), "ok": ok})
        print(("[OK]  " if ok else "[FAIL]") + f" {name}: {fmt(q(got))} vs {fmt(q(exp))}")

    for ent in ("P", "S1", "S2"):
        check(f"{ENTITY_SHORT[ent]}试算平衡（借−贷=0）", balance_check(led[ent]), 0)

    bs = bs_rows(merged)
    check("合并资产负债表：资产总计 = 负债和所有者权益总计",
          bs["资产总计"], bs["负债合计"] + sum((bs[n] for n in ["股本", "资本公积", "盈余公积",
                                                            "一般风险准备", "未分配利润"]), Z))

    isr = is_rows(merged)
    np_s2 = is_rows(led["S2"])["净利润"]
    minority = q(np_s2 * (D("1") - HOLDING["S2"]))
    report["minority"] = str(minority)
    report["parent_net_profit"] = str(isr["净利润"] - minority)

    cf = cash_flow_direct()
    cf_total = sum(cf.values(), Z)
    cash_end = total(merged, ["1001", "1002", "1012"])
    report["cash_flow"] = {k: str(v) for k, v in sorted(cf.items())}
    report["cash_flow_total"] = str(cf_total)

    # 货币资金：期初（合并）+ 现金流净额 = 期末（合并，含内部往来抵消不影响现金）
    cash_open = sum((q(OPENING[en].get(c, "0")) for en in OPENING for c in CASH), Z)
    check("合并现金流量表净增加额 = 货币资金期末 − 期初",
          cf_total, cash_end - cash_open)

    # ---- 输出 ----
    print("\n===== 合并资产负债表 =====")
    for n in BS_ASSET_ORDER:
        print(f"  {n:<22}{fmt(bs[n])}")
    print("\n===== 合并利润表 =====")
    for n in ["营业收入", "营业成本", "税金及附加", "销售费用", "管理费用", "研发费用",
              "财务费用", "其他收益", "投资收益", "信用减值损失", "资产减值损失",
              "营业利润", "营业外收入", "营业外支出", "利润总额", "所得税费用", "净利润"]:
        print(f"  {n:<22}{fmt(isr[n])}")
    print(f"  少数股东损益{'':<14}{fmt(minority)}")
    print(f"  归属于母公司股东的净利润  {fmt(isr['净利润'] - minority)}")
    print("\n===== 合并现金流量表（直接法） =====")
    for k, v in sorted(cf.items()):
        print(f"  {k:<40}{fmt(v)}")
    print(f"  {'净增加额':<40}{fmt(cf_total)}")

    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "consolidation.json"), "w", encoding="utf-8") as fh:
        json.dump({
            "eliminations": elims,
            "merged_trial_balance": {c: str(v) for c, v in sorted(merged.items())},
        }, fh, ensure_ascii=False, indent=2)
    with open(os.path.join(OUT, "checks.json"), "w", encoding="utf-8") as fh:
        json.dump(report, fh, ensure_ascii=False, indent=2)
    print(f"\n产物已写入 {OUT}")


if __name__ == "__main__":
    main()
