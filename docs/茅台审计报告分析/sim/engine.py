# 7. 报表编制
# ---------------------------------------------------------------------------
def bs_rows(led: dict[str, Decimal], *, close_profit: bool = True) -> dict[str, Decimal]:
    out: dict[str, Decimal] = {}
    for name, codes in BS_ASSET:
        out[name] = total(led, codes)          # 资产：借方余额为正
    for name, codes in BS_LIAB:
        out[name] = -total(led, codes)         # 负债：贷方余额为正
    for name, codes in BS_EQUITY:
        out[name] = -total(led, codes)
    if close_profit:
        # 合并底稿内损益类科目尚未结转，未分配利润期末 = 期初 + 本年净利润
        out["未分配利润"] = out["未分配利润"] + is_rows(led)["净利润"]
    out["流动资产合计"] = sum((out[n] for n in CURRENT_ASSETS), Z)
    out["非流动资产合计"] = (out["长期股权投资"] + out["固定资产"] + out["在建工程"]
                          + out["无形资产"] + out["长期待摊费用"] + out["递延所得税资产"])
    out["资产总计"] = out["流动资产合计"] + out["非流动资产合计"]
    out["流动负债合计"] = sum((out[n] for n in CURRENT_LIABS), Z)
    out["非流动负债合计"] = out["租赁负债"] + out["递延收益"]
    out["负债合计"] = out["流动负债合计"] + out["非流动负债合计"]
    return out


INCOME_CODES = {"6001", "6051", "6111", "6117", "6301"}


def is_rows(led: dict[str, Decimal]) -> dict[str, Decimal]:
    raw = {}
    for name, codes in IS_LINES:
        if set(codes) <= INCOME_CODES:
            raw[name] = -total(led, codes)     # 收入：贷方余额为正
        else:
            raw[name] = total(led, codes)      # 成本费用：借方余额为正
    out = dict(raw)
    out["营业利润"] = (raw["营业收入"] - raw["营业成本"] - raw["税金及附加"]
                    - raw["销售费用"] - raw["管理费用"] - raw["研发费用"] - raw["财务费用"]
                    + raw["其他收益"] + raw["投资收益"]
                    - raw["信用减值损失"] - raw["资产减值损失"])
    out["利润总额"] = out["营业利润"] + raw["营业外收入"] - raw["营业外支出"]
    out["净利润"] = out["利润总额"] - raw["所得税费用"]
    return out


def cash_flow_direct(*, consolidate_internal: bool = True) -> dict[str, Decimal]:
    direct: dict[str, Decimal] = defaultdict(lambda: Z)
    for entry in ENTRIES:
        cf = entry["dims"].get("cf")
        if not cf:
            continue
        if consolidate_internal and entry["dims"].get("src") in INTERNAL_CASH_SRC:
            continue
        net = sum((q(l[1] or 0) - q(l[2] or 0)) for l in entry["lines"] if l[0] in CASH)
        if net:
            direct[cf] += net
    return {k: q(v) for k, v in direct.items()}


