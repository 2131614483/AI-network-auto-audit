# 5. 记账与试算平衡
# ---------------------------------------------------------------------------
def build_ledger() -> dict[str, dict[str, Decimal]]:
    led: dict[str, dict[str, Decimal]] = {}
    for ent, opening in OPENING.items():
        led[ent] = {c: q(v) for c, v in opening.items()}
    for entry in ENTRIES:
        bal = led[entry["entity"]]
        dr = sum((q(l[1]) for l in entry["lines"] if l[1]), Z)
        cr = sum((q(l[2]) for l in entry["lines"] if l[2]), Z)
        if dr != cr:
            raise AssertionError(f"分录不平：{entry['memo']} 借{dr} 贷{cr}")
        for code, d, c in entry["lines"]:
            bal[code] = bal.get(code, Z) + q(d or 0) - q(c or 0)
    return led


def total(led: dict[str, Decimal], codes) -> Decimal:
    return sum((led.get(c, Z) for c in codes), Z)


def credit_amount(led: dict[str, Decimal], codes) -> Decimal:
    """收入 / 费用类为贷方余额（负），返回正向金额。"""
    return -total(led, codes)


def balance_check(led: dict[str, Decimal]) -> Decimal:
    return sum(led.values(), Z)


# ---------------------------------------------------------------------------
# 6. 合并工作底稿
# ---------------------------------------------------------------------------
def consolidate(led: dict[str, dict[str, Decimal]], internal_ar=None):
    merged: dict[str, Decimal] = defaultdict(lambda: Z)
    for ent in led:
        for code, v in led[ent].items():
            merged[code] += v

    elims: list[dict] = []

    def elim(memo: str, kind: str, lines: list[tuple[str, str, str]]) -> None:
        for code, d, c in lines:
            merged[code] = merged.get(code, Z) + q(d or 0) - q(c or 0)
        elims.append({"memo": memo, "kind": kind,
                      "amount": str(sum((q(l[1]) for l in lines if l[1]), Z)),
                      "lines": [[l[0], l[1] or "0", l[2] or "0"] for l in lines]})

    elim("抵消内部商品销售：母公司→黔岭销售", "内部购销",
         [("6001", "1000000000", None), ("6401", None, "1000000000")])
    elim("抵消内部商品销售：黔岭包装→母公司", "内部购销",
         [("6001", "260000000", None), ("6401", None, "260000000")])
    for name, amt in (internal_ar if internal_ar is not None else INTERNAL_AR).items():
        elim(f"抵消内部应收应付：{name}", "内部往来",
             [("2202", amt, None), ("1122", None, amt)])
    elim("抵消内部股利与母公司投资收益", "内部股利",
         [("6111", "80000000", None), ("4104", None, "80000000")])
    lti = sum((led[en].get("1501", Z) for en in led if en != "OPEN"), Z)
    elim("抵消母公司对子公司的长期股权投资", "权益抵消",
         [("1501", None, str(lti))])

    merged = {k: q(v) for k, v in merged.items()}
    return merged, elims


