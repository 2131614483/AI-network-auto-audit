def verify() -> None:
    print("\n【高难度实验组 · 生成自检】")
    for ent in ENTITY:
        s = balance_check(LED[ent])
        print(f"  {'OK ' if s == 0 else 'ERR'} {ENTITY[ent]['name']:<16} 试算平衡（借−贷 = {num(s)}）")
    ism, bsm, _, elims = merged_view()
