    ok = bsm["资产总计"] == bsm["负债合计"] + eq
    print(f"  {'OK ' if ok else 'ERR'} 合并：资产 {num(bsm['资产总计'])} = 负债 "
          f"{num(bsm['负债合计'])} + 权益 {num(eq)}")

    print("\n  · 季度对外毛利率（做分析性程序时会看到的东西）：")
    prev = None
    for qt in ("Q1", "Q2", "Q3", "Q4"):
        rev = sum((q(cr) for en in ENTRIES
                   if en["entity"] in ("P", "S1") and en["dims"].get("qt") == qt
                   and not en["dims"].get("src")
                   for c, dr, cr in en["lines"] if c == "6001" and cr), Z)
        cst = sum((q(dr) for en in ENTRIES
                   if en["entity"] in ("P", "S1") and en["dims"].get("qt") == qt
                   and not en["dims"].get("src")
                   for c, dr, cr in en["lines"] if c == "6401" and dr), Z)
        gp = q((D(1) - cst / rev) * 100) if rev else Z
        delta = f"   （较上季 {q(gp - prev):+} pct）" if prev is not None else ""
        prev = gp
        print(f"      {qt}  收入 {num(rev):>18}   毛利率 {gp:>7}%{delta}")

    inv_o = sum((OPENING[e].get(c, Z) for e in ENTITY for c in ("1401", "1402", "1405", "1471")), Z)
    inv_e = sum((LED[e].get(c, Z) for e in ENTITY for c in ("1401", "1402", "1405", "1471")), Z)
