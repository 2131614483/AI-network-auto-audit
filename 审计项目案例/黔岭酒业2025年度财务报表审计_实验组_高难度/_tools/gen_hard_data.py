def num(x) -> str:
    """CSV 金额列：纯数字，不带千分位（贴近真实系统导出）。"""
    return f"{q(x):.2f}"


def led_flow(code: str, ent: str) -> tuple[Decimal, Decimal, Decimal]:
    o = OPENING[ent].get(code, Z)
    d = sum((q(l1) for en in ENTRIES if en["entity"] == ent
             for c, l1, l2 in en["lines"] if c == code and l1), Z)
    c_ = sum((q(l2) for en in ENTRIES if en["entity"] == ent
              for c, l1, l2 in en["lines"] if c == code and l2), Z)
    return o, d, c_


