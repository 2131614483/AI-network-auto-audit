def _mi(y: int, mo: int) -> int:
    return y * 12 + mo


def fa_annual(c: dict) -> Decimal:
    return q(D(c["cost"]) * (D(1) - D(c["rate"]) / D(100)) / D(c["life"]))


def fa_cap(c: dict) -> Decimal:
    return q(D(c["cost"]) * (D(1) - D(c["rate"]) / D(100)))


def fa_open(c: dict) -> Decimal:
    """上年末累计折旧。"""
    sy, sm = int(c["start"][:4]), int(c["start"][5:7])
    months = max(_mi(*PRIOR) - _mi(sy, sm), 0)
    return min(q(fa_annual(c) / D(12) * D(months)), fa_cap(c))


def fa_due(c: dict) -> Decimal:
    """本期应有折旧（直线法，当月增加次月起计提，封顶应计折旧总额）。"""
    sy, sm = int(c["start"][:4]), int(c["start"][5:7])
    months = 12 if sy < 2025 else max(_mi(*PERIOD) - _mi(sy, sm), 0)
    due = q(fa_annual(c) / D(12) * D(months))
    remaining = fa_cap(c) - fa_open(c)
    return min(due, max(remaining, Z))


def fa_book(c: dict) -> Decimal:
    """账面本期计提额：模拟客户实际账务处理。"""
    base = fa_due(c)
    if c.get("over_dep"):
        return q(base + fa_annual(c))          # 年限已满，仍按整年计提
    if c.get("delay_months"):
        return q(base - fa_annual(c) / D(12) * D(c["delay_months"]))
    return base


