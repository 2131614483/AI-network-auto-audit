def by_tier() -> dict[str, list[str]]:
    out: dict[str, list[str]] = {t: [] for t in TIER_ORDER}
    for it in ISSUES:
        out[it["tier"]].append(it["id"])
    return out


def by_rule() -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for it in ISSUES:
        if it["auto_rule"]:
            out.setdefault(it["auto_rule"], []).append(it["id"])
    return out


def by_group() -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for it in ISSUES:
        out.setdefault(it["group"], []).append(it["id"])
    return out


def summary() -> dict:
    import collections
    natures = collections.Counter(i["nature"] for i in ISSUES)
    sevs = collections.Counter(i["severity"] for i in ISSUES)
    disp = collections.Counter(i["disposition"] for i in ISSUES)
    need_adj = sum(int(i["amount"]) for i in ISSUES if i["disposition"] == "需调整")
    stealthy = sum(1 for i in ISSUES if i["tier"] in ("T3", "T4", "T5"))
    return {
        "总数": len(ISSUES),
        "按性质": dict(natures),
        "按严重程度": dict(sevs),
        "按处理方式": dict(disp),
        "需调整金额合计": need_adj,
        "分层项数": {t: len(by_tier()[t]) for t in TIER_ORDER},
        "规则可自动检出": len(by_rule()),
        "需推理层级项数": stealthy,
        "噪音项数": len(NOISE),
        "重要性水平": MATERIALITY,
        "SAD限额": SAD_LIMIT,
    }


