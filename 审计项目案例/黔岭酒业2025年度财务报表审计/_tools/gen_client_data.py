        neg = [(c, m(v)) for c, v in LED[ent].items()
               if v < 0 and ACCOUNTS.get(c, ("", "?", ""))[1] in ("asset",)]
        if neg:
            print(f"     ⚠ 资产类科目出现贷方余额：{neg}")

