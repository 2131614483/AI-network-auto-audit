def fa_annual(c: dict) -> Decimal:
    """年折旧额（直线法，残值率）。"""
    return q((q(c["cost"]) * (D(1) - D(c["salvage"]) / D(100))) / D(c["life"]))


def fa_cap(c: dict) -> Decimal:
    return q(q(c["cost"]) * (D(1) - D(c["salvage"]) / D(100)))


def fa_dep_open(c: dict) -> Decimal:
    """2024-12-31 累计折旧：转固次月起计提，封顶到应计折旧总额。"""
    y, mo = int(c["start"][:4]), int(c["start"][5:7])
    months = max(0, months_between(y, mo, 2024, 12))
    return min(q(fa_annual(c) / D(12) * D(months)), fa_cap(c))


def fa_dep_due(c: dict) -> Decimal:
    """2025 年度应有折旧。"""
    y, mo = int(c["start"][:4]), int(c["start"][5:7])
    if y > 2025:
        return Z
    start_month = mo + 1 if y == 2025 else 1          # 当月增加当月不提
    if y < 2025:
        start_month = 1
    months = max(0, months_between(2025, start_month, 2025, 12) + 1) if start_month <= 12 else 0
    remaining = fa_cap(c) - fa_dep_open(c)
    return min(q(fa_annual(c) / D(12) * D(months)), max(Z, remaining))


