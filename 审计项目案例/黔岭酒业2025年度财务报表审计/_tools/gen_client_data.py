def build_ledger():
    led = {ent: {c: q(v) for c, v in bal.items()} for ent, bal in OPENING.items()}
    for en in ENTRIES:
        bal = led[en["entity"]]
        dr = sum((q(l[1]) for l in en["lines"] if l[1]), Z)
        cr = sum((q(l[2]) for l in en["lines"] if l[2]), Z)
        assert dr == cr, f"分录不平：{en['memo']} 借{dr} 贷{cr}"
        for code, d, c in en["lines"]:
            bal[code] = bal.get(code, Z) + q(d or 0) - q(c or 0)
    return led


