def m(x) -> str:
    return f"{q(x):,.2f}"


def w(rel: str, header: list[str], rows: list[list]) -> None:
    path = os.path.join(DATA, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8-sig") as fh:
        wr = csv.writer(fh)
        wr.writerow(header)
        wr.writerows(rows)


def app(rel: str, rows: list[list]) -> None:
    with open(os.path.join(DATA, rel), "a", newline="", encoding="utf-8-sig") as fh:
        csv.writer(fh).writerows(rows)


def txt(rel: str, body: str) -> None:
    path = os.path.join(DATA, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(body.lstrip("\n"))


def read(rel: str) -> list[list]:
    with open(os.path.join(DATA, rel), encoding="utf-8-sig", newline="") as fh:
        return list(csv.reader(fh))


