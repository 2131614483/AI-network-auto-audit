def install_idle_card() -> Decimal:
    """把闲置资产并入卡片台账，并重算对照组依赖的派生量。"""
    base.FA_CARDS.append(IDLE_CARD)
    for c in base.FA_CARDS:
        c["_annual"] = base.fa_annual(c)
        c["_cap"] = base.fa_cap(c)
        c["_open"] = base.fa_dep_open(c)
        c["_due"] = base.fa_dep_due(c)
        c["_book"] = q(c["dep_book"]) if "dep_book" in c else c["_due"]
    for e in ENTITY:
        base.FA_COST_END[e] = sum((q(c["cost"]) for c in base.FA_CARDS if c["ent"] == e), Z)
        base.FA_COST_ADD[e] = sum((q(c["cost"]) for c in base.FA_CARDS
                                   if c["ent"] == e and c["start"] >= "2025-01-01"), Z)
        base.FA_DEP_OPEN[e] = sum((c["_open"] for c in base.FA_CARDS if c["ent"] == e), Z)
    base.OPENING = base.opening_balances()
    return q(q(IDLE_CARD["cost"]) - (IDLE_CARD["_open"] + IDLE_CARD["_book"]))


